#!/usr/bin/env python3
"""
Update Google Scholar citation counts for publications in _data/publications.yaml.

Uses SerpAPI's google_scholar engine. Writes a sidecar cache file at
_data/citation_cache.yaml keyed by publication `id`; the main publications.yaml
is left untouched so hand-maintained formatting is preserved. Jekyll loads the
cache as site.data.citation_cache.

Usage:
    export SERPAPI_KEY=...
    python3 bin/update_citations.py --sample 5            # random sample
    python3 bin/update_citations.py --id molmo            # single paper
    python3 bin/update_citations.py --limit 10 --force    # first 10, ignore cache
    python3 bin/update_citations.py                       # all papers

Requirements: pyyaml. On this machine use:
    /opt/homebrew/anaconda3/bin/python3 bin/update_citations.py ...
"""

import argparse
import difflib
import json
import os
import random
import sys
import time
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PUBLICATIONS_PATH = ROOT / "_data" / "publications.yaml"
CACHE_PATH = ROOT / "_data" / "citation_cache.yaml"
SERPAPI_URL = "https://serpapi.com/search.json"
STALE_AFTER_DAYS = 7
REQUEST_DELAY_SEC = 1.0
REQUEST_TIMEOUT_SEC = 30
TITLE_MATCH_STRONG = 0.8
TITLE_MATCH_WEAK = 0.6


def load_publications():
    with open(PUBLICATIONS_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_cache():
    if not CACHE_PATH.exists():
        return {}
    with open(CACHE_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def save_cache(cache):
    with open(CACHE_PATH, "w", encoding="utf-8") as f:
        f.write(
            "# Auto-generated by bin/update_citations.py — do not edit by hand.\n"
            "# Citation counts and match metadata from Google Scholar (via SerpAPI),\n"
            "# keyed by publication id from _data/publications.yaml.\n"
        )
        yaml.safe_dump(
            cache, f, sort_keys=True, allow_unicode=True, default_flow_style=False
        )


def clean_title(title):
    """Unescape our YAML conventions so the title reads naturally for a search."""
    if not title:
        return ""
    return title.replace("&colon;", ":").strip().strip('"').strip()


def query_scholar(title, api_key):
    params = {"engine": "google_scholar", "q": title, "api_key": api_key}
    url = SERPAPI_URL + "?" + urllib.parse.urlencode(params)
    with urllib.request.urlopen(url, timeout=REQUEST_TIMEOUT_SEC) as resp:
        body = resp.read().decode("utf-8")
    return json.loads(body)


def compute_match_confidence(pub_title, pub_authors, top):
    """Return ("high"|"low"|"none", title_similarity, author_hit)."""
    top_title = (top.get("title") or "").lower()
    sim = difflib.SequenceMatcher(None, pub_title.lower(), top_title).ratio()

    top_info = top.get("publication_info", {}) or {}
    author_blob = " ".join(
        [
            " ".join(a.get("name", "") for a in (top_info.get("authors") or [])),
            top_info.get("summary", "") or "",
            top.get("snippet", "") or "",
        ]
    ).lower()
    has_ccb = "callison" in author_blob

    if sim >= TITLE_MATCH_STRONG and has_ccb:
        level = "high"
    elif sim >= TITLE_MATCH_WEAK or has_ccb:
        level = "low"
    else:
        level = "none"
    return level, round(sim, 3), has_ccb


def process_one(pub, cache, api_key, force, dry_run):
    """Return dict of status info for logging."""
    pub_id = pub.get("id")
    title_raw = pub.get("title") or ""
    title = clean_title(title_raw)

    if not pub_id or not title:
        return {"status": "skip", "reason": "missing id or title"}

    entry = cache.get(pub_id) or {}
    if not force and entry.get("citation_count_updated"):
        updated = datetime.fromisoformat(entry["citation_count_updated"])
        if datetime.now(timezone.utc) - updated.replace(
            tzinfo=updated.tzinfo or timezone.utc
        ) < timedelta(days=STALE_AFTER_DAYS):
            return {
                "status": "cached",
                "citation_count": entry.get("citation_count"),
                "confidence": entry.get("match_confidence"),
            }

    try:
        data = query_scholar(title, api_key)
    except Exception as exc:
        return {"status": "error", "reason": str(exc)[:160]}

    results = data.get("organic_results") or []
    if not results:
        new_entry = {
            "citation_count": None,
            "citation_count_updated": datetime.now(timezone.utc)
            .replace(microsecond=0)
            .isoformat(),
            "scholar_cluster_id": None,
            "scholar_result_id": None,
            "scholar_result_title": None,
            "match_confidence": "none",
            "title_similarity": 0.0,
        }
        if not dry_run:
            cache[pub_id] = new_entry
        return {"status": "no_results", "citation_count": None, "confidence": "none"}

    top = results[0]
    confidence, sim, has_ccb = compute_match_confidence(title, pub.get("authors"), top)

    cited_by = (top.get("inline_links") or {}).get("cited_by") or {}
    count = cited_by.get("total", 0) if "total" in cited_by else (
        0 if cited_by else None
    )
    cluster_id = cited_by.get("cites_id")

    new_entry = {
        "citation_count": count,
        "citation_count_updated": datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat(),
        "scholar_cluster_id": cluster_id,
        "scholar_result_id": top.get("result_id"),
        "scholar_result_title": top.get("title"),
        "match_confidence": confidence,
        "title_similarity": sim,
    }
    if not dry_run:
        cache[pub_id] = new_entry
    return {
        "status": "fetched",
        "citation_count": count,
        "confidence": confidence,
        "similarity": sim,
        "scholar_title": top.get("title"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--sample", type=int, help="Process a random sample of N papers")
    parser.add_argument("--id", help="Process a single paper by id")
    parser.add_argument("--limit", type=int, help="Process only the first N papers after filtering")
    parser.add_argument("--force", action="store_true", help="Ignore cache freshness")
    parser.add_argument("--dry-run", action="store_true", help="Do not write cache")
    parser.add_argument("--api-key", help="SerpAPI key (else SERPAPI_KEY env var)")
    parser.add_argument("--verbose", action="store_true", help="Print full top result")
    parser.add_argument("--seed", type=int, default=None, help="Random seed for --sample")
    args = parser.parse_args()

    api_key = args.api_key or os.environ.get("SERPAPI_KEY")
    if not api_key:
        sys.exit("No API key. Set SERPAPI_KEY env var or pass --api-key.")

    pubs = load_publications()
    if not isinstance(pubs, list):
        sys.exit(f"Expected a list at the top of {PUBLICATIONS_PATH}, got {type(pubs)}")

    # Require an id to be meaningful
    pubs = [p for p in pubs if isinstance(p, dict) and p.get("id")]

    if args.id:
        pubs = [p for p in pubs if p.get("id") == args.id]
        if not pubs:
            sys.exit(f"No publication with id={args.id}")
    if args.sample:
        if args.seed is not None:
            random.seed(args.seed)
        pubs = random.sample(pubs, min(args.sample, len(pubs)))
    if args.limit:
        pubs = pubs[: args.limit]

    cache = load_cache()

    total = len(pubs)
    if total == 0:
        sys.exit("No publications to process after filtering.")

    print(f"Processing {total} publication(s). Cache: {CACHE_PATH}")
    print("-" * 100)

    need_api = 0
    for i, pub in enumerate(pubs, 1):
        pub_id = pub.get("id")
        short_title = clean_title(pub.get("title") or "")[:60]
        result = process_one(pub, cache, api_key, args.force, args.dry_run)
        status = result["status"]
        if status == "fetched":
            need_api += 1
            print(
                f"[{i:3}/{total}] {pub_id:45} "
                f"count={result['citation_count']!s:>6} "
                f"conf={result['confidence']:<4} "
                f"sim={result['similarity']:.2f}  "
                f"{short_title}"
            )
            if args.verbose:
                print(f"         scholar title: {result.get('scholar_title')}")
        elif status == "cached":
            print(
                f"[{i:3}/{total}] {pub_id:45} "
                f"count={result['citation_count']!s:>6} conf={result.get('confidence','')!s:<4} "
                f"CACHED  {short_title}"
            )
        elif status == "no_results":
            need_api += 1
            print(f"[{i:3}/{total}] {pub_id:45} NO RESULTS  {short_title}")
        elif status == "error":
            need_api += 1
            print(f"[{i:3}/{total}] {pub_id:45} ERROR: {result['reason']}")
        else:
            print(f"[{i:3}/{total}] {pub_id:45} SKIP: {result.get('reason','')}")

        if status in ("fetched", "no_results", "error"):
            time.sleep(REQUEST_DELAY_SEC)

    if not args.dry_run:
        save_cache(cache)
        print(f"\nWrote {CACHE_PATH} ({len(cache)} total entries)")
    else:
        print("\n[dry-run] Cache not written")

    print(f"SerpAPI calls: {need_api}")


if __name__ == "__main__":
    main()
