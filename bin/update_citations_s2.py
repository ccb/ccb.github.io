#!/usr/bin/env python3
"""
Update Semantic Scholar citation counts for publications in _data/publications.yaml.

Mirrors bin/update_citations.py but uses the Semantic Scholar Graph API.

Three-phase lookup, in priority order:
  1. If the publication has a real DOI in publications.yaml (not null and not
     the string "pending"), look up via GET /graph/v1/paper/DOI:<doi>.
     Zero-ambiguity, highest priority.
  2. Else if the url is an arxiv link, look up via /paper/arXiv:<id>.
  3. Otherwise, use GET /graph/v1/paper/search/match?query=<title>.

Verifies "callison" appears in returned authors. Cache is sidecar at
_data/citation_cache_s2.yaml, keyed by publication id (parallel to the
Google Scholar cache).

Usage:
    export S2_API_KEY=...
    /opt/homebrew/anaconda3/bin/python3 bin/update_citations_s2.py --sample 5
    /opt/homebrew/anaconda3/bin/python3 bin/update_citations_s2.py --id molmo --force
    /opt/homebrew/anaconda3/bin/python3 bin/update_citations_s2.py            # full run

Attribution: Per S2's terms, the site should credit Semantic Scholar where
data is displayed (e.g. "Citation counts via Semantic Scholar.").
"""

import argparse
import json
import os
import random
import re
import sys
import time
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PUBLICATIONS_PATH = ROOT / "_data" / "publications.yaml"
CACHE_PATH = ROOT / "_data" / "citation_cache_s2.yaml"
S2_BASE = "https://api.semanticscholar.org/graph/v1"
FIELDS = "paperId,title,authors,year,venue,citationCount,influentialCitationCount,externalIds"
STALE_AFTER_DAYS = 7
REQUEST_DELAY_SEC = 1.5  # S2 limit: 1 req/s; 1.5s adds headroom
REQUEST_TIMEOUT_SEC = 30
_last_request_time = 0.0
MATCH_SCORE_STRONG = 0.8

# Match e.g. https://arxiv.org/abs/2503.08600 or .../pdf/2509.22646 or .../html/2509.22646v1
ARXIV_RE = re.compile(
    r"arxiv\.org/(?:abs|pdf|html)/([a-z\-]+(?:\.[A-Z]{2})?/\d{7}|\d{4}\.\d{4,5})",
    re.IGNORECASE,
)


def load_publications():
    with open(PUBLICATIONS_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_cache():
    if not CACHE_PATH.exists():
        return {}
    with open(CACHE_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def save_cache(cache):
    with open(CACHE_PATH, "w", encoding="utf-8") as f:
        f.write(
            "# Auto-generated by bin/update_citations_s2.py — do not edit by hand.\n"
            "# Citation data from Semantic Scholar Graph API, keyed by publication\n"
            "# id from _data/publications.yaml.\n"
        )
        yaml.safe_dump(
            cache, f, sort_keys=True, allow_unicode=True, default_flow_style=False
        )


def clean_title(title):
    if not title:
        return ""
    return title.replace("&colon;", ":").strip().strip('"').strip()


def extract_arxiv_id(url):
    if not url:
        return None
    m = ARXIV_RE.search(url)
    if not m:
        return None
    arxiv_id = m.group(1)
    # Strip a trailing version like v1, v2 from new-style ids
    arxiv_id = re.sub(r"v\d+$", "", arxiv_id)
    return arxiv_id


def s2_request(path, api_key, params=None, _attempt=0):
    """All HTTP traffic to S2 funnels through here so we can rate-limit globally.

    Transparently retries 429 responses with exponential backoff (up to 4 tries).
    """
    global _last_request_time
    elapsed = time.monotonic() - _last_request_time
    if elapsed < REQUEST_DELAY_SEC:
        time.sleep(REQUEST_DELAY_SEC - elapsed)
    url = S2_BASE + path
    if params:
        url += "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"x-api-key": api_key})
    try:
        with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT_SEC) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        if e.code == 429 and _attempt < 4:
            backoff = 10 * (2 ** _attempt)  # 10, 20, 40, 80 seconds
            print(f"    [rate-limited, backing off {backoff}s]", flush=True)
            time.sleep(backoff)
            _last_request_time = time.monotonic()
            return s2_request(path, api_key, params, _attempt + 1)
        raise
    finally:
        _last_request_time = time.monotonic()


def lookup_by_arxiv(arxiv_id, api_key):
    return s2_request(f"/paper/arXiv:{arxiv_id}", api_key, {"fields": FIELDS})


def lookup_by_doi(doi, api_key):
    # S2's path uses URL-encoded DOI; their endpoint accepts /paper/DOI:<doi>
    return s2_request(f"/paper/DOI:{doi}", api_key, {"fields": FIELDS})


def lookup_by_title(title, api_key):
    return s2_request(
        "/paper/search/match", api_key, {"query": title, "fields": FIELDS}
    )


def has_ccb(paper):
    authors = paper.get("authors") or []
    blob = " ".join((a.get("name") or "") for a in authors).lower()
    return "callison" in blob


def make_entry(paper, lookup_method, match_score=None):
    return {
        "citation_count": paper.get("citationCount"),
        "influential_citation_count": paper.get("influentialCitationCount"),
        "citation_count_updated": datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat(),
        "s2_paper_id": paper.get("paperId"),
        "s2_match_title": paper.get("title"),
        "s2_match_score": match_score,
        "s2_year": paper.get("year"),
        "s2_venue": paper.get("venue"),
        "external_ids": paper.get("externalIds") or {},
        "lookup_method": lookup_method,
        "match_confidence": "high" if has_ccb(paper) else "low",
    }


def process_one(pub, cache, api_key, force, dry_run):
    pub_id = pub.get("id")
    title = clean_title(pub.get("title") or "")
    if not pub_id or not title:
        return {"status": "skip", "reason": "missing id or title"}

    entry = cache.get(pub_id) or {}
    if not force and entry.get("citation_count_updated"):
        try:
            updated = datetime.fromisoformat(entry["citation_count_updated"])
            if datetime.now(timezone.utc) - updated.replace(
                tzinfo=updated.tzinfo or timezone.utc
            ) < timedelta(days=STALE_AFTER_DAYS):
                return {
                    "status": "cached",
                    "citation_count": entry.get("citation_count"),
                    "confidence": entry.get("match_confidence"),
                }
        except Exception:
            pass

    raw_doi = pub.get("doi")
    doi = raw_doi if isinstance(raw_doi, str) and raw_doi and raw_doi != "pending" else None
    arxiv_id = extract_arxiv_id(pub.get("url") or "")
    paper = None
    method = None
    match_score = None
    try:
        if doi:
            try:
                paper = lookup_by_doi(doi, api_key)
                method = "doi"
            except urllib.error.HTTPError as e:
                if e.code != 404:
                    raise
                paper = None
        if not paper and arxiv_id:
            try:
                paper = lookup_by_arxiv(arxiv_id, api_key)
                method = "arxiv"
            except urllib.error.HTTPError as e:
                if e.code != 404:
                    raise
                paper = None
        if not paper:
            resp = lookup_by_title(title, api_key)
            paper = (resp.get("data") or [None])[0]
            method = "title"
            match_score = paper.get("matchScore") if paper else None
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")[:160]
        return {"status": "error", "reason": f"HTTP {e.code}: {body}"}
    except Exception as e:
        return {"status": "error", "reason": str(e)[:160]}

    if not paper:
        new_entry = {
            "citation_count": None,
            "influential_citation_count": None,
            "citation_count_updated": datetime.now(timezone.utc)
            .replace(microsecond=0)
            .isoformat(),
            "s2_paper_id": None,
            "s2_match_title": None,
            "s2_match_score": None,
            "lookup_method": method,
            "match_confidence": "none",
        }
        if not dry_run:
            cache[pub_id] = new_entry
        return {"status": "no_match", "citation_count": None, "confidence": "none"}

    new_entry = make_entry(paper, method, match_score)
    if not dry_run:
        cache[pub_id] = new_entry
    return {
        "status": "fetched",
        "citation_count": new_entry["citation_count"],
        "influential": new_entry["influential_citation_count"],
        "confidence": new_entry["match_confidence"],
        "method": method,
        "s2_title": new_entry["s2_match_title"],
        "match_score": match_score,
    }


def main():
    parser = argparse.ArgumentParser(description="Fetch S2 citations for publications.yaml")
    parser.add_argument("--sample", type=int, help="Process a random sample of N papers")
    parser.add_argument("--id", help="Process a single paper by id")
    parser.add_argument("--limit", type=int, help="Process the first N after filtering")
    parser.add_argument("--force", action="store_true", help="Ignore cache freshness")
    parser.add_argument("--dry-run", action="store_true", help="Do not write cache")
    parser.add_argument("--api-key", help="S2 API key (else S2_API_KEY env var)")
    parser.add_argument("--seed", type=int, default=None, help="Random seed for --sample")
    parser.add_argument("--verbose", action="store_true", help="Print extra info")
    args = parser.parse_args()

    api_key = args.api_key or os.environ.get("S2_API_KEY")
    if not api_key:
        sys.exit("No API key. Set S2_API_KEY env var or pass --api-key.")

    pubs = load_publications()
    if not isinstance(pubs, list):
        sys.exit(f"Expected a list at the top of {PUBLICATIONS_PATH}")
    pubs = [p for p in pubs if isinstance(p, dict) and p.get("id")]

    if args.id:
        pubs = [p for p in pubs if p.get("id") == args.id]
        if not pubs:
            sys.exit(f"No publication with id={args.id}")
    if args.sample:
        if args.seed is not None:
            random.seed(args.seed)
        pubs = random.sample(pubs, min(args.sample, len(pubs)))
    if args.limit:
        pubs = pubs[: args.limit]

    cache = load_cache()
    total = len(pubs)
    if total == 0:
        sys.exit("No publications to process after filtering.")

    print(f"Processing {total} publication(s). Cache: {CACHE_PATH}")
    print("-" * 110)

    api_calls = 0
    save_every = 25
    for i, pub in enumerate(pubs, 1):
        pub_id = pub.get("id")
        short_title = clean_title(pub.get("title") or "")[:55]
        result = process_one(pub, cache, api_key, args.force, args.dry_run)
        status = result["status"]
        if status == "fetched":
            api_calls += 1
            ms = result.get("match_score")
            ms_s = f"ms={ms:.2f}" if isinstance(ms, (int, float)) else "ms=  - "
            print(
                f"[{i:3}/{total}] {pub_id:42} "
                f"c={result['citation_count']!s:>5} "
                f"i={result['influential']!s:>4} "
                f"conf={result['confidence']:<4} "
                f"{result['method']:<6} {ms_s}  {short_title}"
            )
            if args.verbose:
                print(f"           s2 title: {result.get('s2_title')}")
        elif status == "cached":
            print(
                f"[{i:3}/{total}] {pub_id:42} "
                f"c={result['citation_count']!s:>5} "
                f"conf={result.get('confidence',''):<4} CACHED  {short_title}"
            )
        elif status == "no_match":
            api_calls += 1
            print(f"[{i:3}/{total}] {pub_id:42} NO MATCH  {short_title}")
        elif status == "error":
            api_calls += 1
            print(f"[{i:3}/{total}] {pub_id:42} ERROR: {result['reason']}")
        else:
            print(f"[{i:3}/{total}] {pub_id:42} SKIP: {result.get('reason','')}")

        # incremental save in case of crash
        if not args.dry_run and api_calls and api_calls % save_every == 0:
            save_cache(cache)

        # rate limiting is now handled inside s2_request()

    if not args.dry_run:
        save_cache(cache)
        print(f"\nWrote {CACHE_PATH} ({len(cache)} total entries)")
    else:
        print("\n[dry-run] Cache not written")
    print(f"S2 API calls: {api_calls}")


if __name__ == "__main__":
    main()
