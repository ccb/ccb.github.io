#!/usr/bin/env python3
"""Apply the user's picks to the citation cache, revert WMT entries, and
remove cache entries that no longer exist in publications.yaml.

Picks (hardcoded from the picklist):
    statistical-natural-language-processing-chapter: none
    hiero-grammar-extraction-with-suffix-arrays: 1
    searchable-translation-memories: 2
    cost-optimization-for-crowdsourcing-translation: 1
    gvdb-d4gx: (deleted from yaml — remove cache entry)
    human-ai-cooperation-healthcare: none
    domain-specific-paraphrases: 1
    shield-of-heroic-memories: none
    llms-and-corpora: none

Also revert WMT 2009/2012/2013 cache entries to match_confidence=none with a note
that Scholar clusters them all under the 2014 paper.
"""

from datetime import datetime, timezone
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
CACHE_PATH = ROOT / "_data" / "citation_cache.yaml"
PICKLIST_PATH = ROOT / "_data" / "citation_review_picklist.yaml"
PUB_PATH = ROOT / "_data" / "publications.yaml"

PICKS = {
    "statistical-natural-language-processing-chapter": "none",
    "hiero-grammar-extraction-with-suffix-arrays": 1,
    "searchable-translation-memories": 2,
    "cost-optimization-for-crowdsourcing-translation": 1,
    "human-ai-cooperation-healthcare": "none",
    "domain-specific-paraphrases": 1,
    "shield-of-heroic-memories": "none",
    "llms-and-corpora": "none",
}

WMT_IDS = [
    "findings-of-the-wmt09-shared-tasks",
    "findings-of-the-wmt12-shared-tasks",
    "findings-of-the-wmt13-shared-tasks",
]


def now_iso():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def main():
    cache = yaml.safe_load(open(CACHE_PATH)) or {}
    picklist = yaml.safe_load(open(PICKLIST_PATH)) or {}
    pubs = yaml.safe_load(open(PUB_PATH)) or []
    live_ids = {p["id"] for p in pubs if isinstance(p, dict) and p.get("id")}

    # Apply picks
    for pid, pick in PICKS.items():
        if pid not in picklist:
            print(f"  skip {pid}: not in picklist")
            continue
        if pick == "none":
            cache[pid] = {
                "citation_count": None,
                "citation_count_updated": now_iso(),
                "match_confidence": "none",
                "scholar_cluster_id": None,
                "scholar_result_id": None,
                "scholar_result_title": None,
                "title_similarity": 0.0,
                "notes": "manually reviewed: no Scholar match",
            }
            print(f"  {pid}: none -> cleared")
            continue
        # Numeric pick
        alts = picklist[pid].get("alternates", [])
        idx = int(pick) - 1
        if idx < 0 or idx >= len(alts):
            print(f"  {pid}: pick {pick} out of range")
            continue
        alt = alts[idx]
        cache[pid] = {
            "citation_count": alt.get("cited_by"),
            "citation_count_updated": now_iso(),
            "scholar_cluster_id": alt.get("cluster_id"),
            "scholar_result_id": alt.get("result_id"),
            "scholar_result_title": alt.get("title"),
            "match_confidence": "high",
            "title_similarity": 1.0,
            "notes": f"manually picked alternate #{pick} from picklist",
        }
        print(
            f"  {pid}: pick {pick} -> '{alt.get('title')[:60]}' "
            f"cites={alt.get('cited_by')}"
        )

    # Revert WMT entries
    for wid in WMT_IDS:
        if wid in cache:
            cache[wid] = {
                "citation_count": None,
                "citation_count_updated": now_iso(),
                "match_confidence": "none",
                "scholar_cluster_id": None,
                "scholar_result_id": None,
                "scholar_result_title": None,
                "title_similarity": 0.0,
                "notes": (
                    "Google Scholar clusters WMT Findings papers by title-minus-year; "
                    "the 2014 cluster dominates. Citation count must be set manually."
                ),
            }
            print(f"  {wid}: reverted to none (Scholar year-clustering)")

    # Remove cache entries whose yaml id no longer exists
    orphans = [k for k in cache.keys() if k not in live_ids]
    for k in orphans:
        del cache[k]
        print(f"  removed orphan cache entry: {k}")

    with open(CACHE_PATH, "w", encoding="utf-8") as f:
        f.write(
            "# Auto-generated by bin/update_citations.py — do not edit by hand.\n"
            "# Citation counts and match metadata from Google Scholar (via SerpAPI),\n"
            "# keyed by publication id from _data/publications.yaml.\n"
        )
        yaml.safe_dump(cache, f, sort_keys=True, allow_unicode=True, default_flow_style=False)
    print(f"\nCache saved ({len(cache)} entries)")


if __name__ == "__main__":
    main()
